/**
 * Render complete sample ecosystems as Markdown (docs/internal/samples/<slug>.md).
 * Uses the curated engine directly (no AI cost). If an AI run exists for the sample
 * (<slug>.ai.json from compare-engines), its categories are listed for comparison.
 *
 *   npx tsx --tsconfig tsconfig.json scripts/render-samples.ts
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { generateAnalysis } from "@/lib/engine";
import { rankCategories, WEIGHT_PRESETS, presetForGrowthPriority } from "@/lib/scoring";
import { executiveOverview, actionPlan } from "@/lib/narrative";
import { TYPE_META, DIRECTION_META } from "@/lib/ui-meta";
import { MemoryStore, setStoreForTesting } from "@/lib/store";
import type { Analysis } from "@/lib/schema";
import { SAMPLES } from "./samples";

setStoreForTesting(new MemoryStore());
const outDir = path.resolve("docs/internal/samples");
mkdirSync(outDir, { recursive: true });

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

async function main() {
  for (const s of SAMPLES) {
    const a = await generateAnalysis(s.input, { forceKnowledgeBase: true });
    const weights = WEIGHT_PRESETS[presetForGrowthPriority(a.profile.growthPriority)].weights;
    const ranked = rankCategories(a.categories, weights);
    const lines: string[] = [];
    lines.push(`# Sample ecosystem: ${a.profile.displayName}`);
    lines.push("");
    lines.push(`> Illustrative sample for beta validation. This is a hypothetical business; no real organisations are named. Generated by the curated engine (profile: **${a.engine.archetypeLabel}**, ${a.engine.matchConfidence} match). Priorities use the "${WEIGHT_PRESETS[presetForGrowthPriority(a.profile.growthPriority)].label}" preset. Scores are strategic heuristics, not forecasts.`);
    lines.push("");
    lines.push(`**Industry:** ${a.profile.industry} · **Area:** ${a.profile.serviceArea} · **Customers:** ${a.profile.idealCustomer}`);
    lines.push("");
    lines.push("## Overview");
    for (const p of executiveOverview(a, ranked)) lines.push("", p);
    lines.push("");
    lines.push("## Ranked relationships");
    lines.push("");
    lines.push("| # | Partner | Type | Direction | Channel | Priority | Who decides | Often overlooked |");
    lines.push("|---|---|---|---|---|---|---|---|");
    ranked.forEach((c, i) =>
      lines.push(
        `| ${i + 1} | ${esc(c.name)} | ${TYPE_META[c.relationshipType].short} | ${DIRECTION_META[c.direction].label} | ${c.channelType} | ${c.priority} (${c.score}) | ${esc(c.decisionMaker ?? "—")} | ${c.overlooked ? "yes" : ""} |`,
      ),
    );
    lines.push("");
    lines.push("## How each relationship works");
    for (const c of ranked) {
      lines.push("", `### ${c.name}`, "");
      lines.push(`*${TYPE_META[c.relationshipType].label} · ${DIRECTION_META[c.direction].label} · ${c.channelType} · ${c.priority} (${c.score})${c.overlooked ? " · often overlooked" : ""}*`, "");
      lines.push(`**Opportunity.** ${c.opportunity}`, "");
      lines.push(`**Why it makes commercial sense.** ${c.rationale}`, "");
      if (c.decisionMaker) lines.push(`**Who decides.** ${c.decisionMaker}`, "");
      lines.push("**Trigger events**", "");
      for (const t of c.triggers) {
        lines.push(`- **${t.event}.** ${t.whyNeed}. *Who notices:* ${t.whoRecognizes}. *Refer when:* ${t.referralMoment}. *Their gain:* ${t.partnerValue}.`);
      }
      lines.push("", `**Mutual value.** ${c.mutualValue}`, "", `**First step.** ${c.approach}`);
      if (c.regulatoryNote) lines.push("", `**Regulatory.** ${c.regulatoryNote}`);
    }
    lines.push("", "## First 10 actions", "");
    for (const p of actionPlan(ranked)) lines.push(`${p.rank}. **${p.name}**: ${p.firstStep} *Watch for:* ${p.watchFor}`);
    lines.push("", "## Guardrails", "");
    for (const g of a.guardrails) lines.push(`- **${g.title}.** ${g.body}`);

    const aiFile = path.join(outDir, `${s.slug}.ai.json`);
    if (existsSync(aiFile)) {
      const ai = JSON.parse(readFileSync(aiFile, "utf8")) as Analysis;
      lines.push("", `## AI comparison (${ai.engine.mode === "ai" ? ai.engine.model : "AI run fell back to curated"})`, "");
      if (ai.engine.mode === "ai") {
        for (const c of rankCategories(ai.categories, weights)) {
          lines.push(`- ${c.name} (${TYPE_META[c.relationshipType].short}, ${c.priority} ${c.score})${c.overlooked ? " · flagged overlooked" : ""}. Decides: ${c.decisionMaker ?? "—"}`);
        }
      } else lines.push(ai.engine.notes.join(" "));
    }
    writeFileSync(path.join(outDir, `${s.slug}.md`), lines.join("\n") + "\n");
    console.log("wrote", s.slug);
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
